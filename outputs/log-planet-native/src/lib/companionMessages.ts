export function randomCompanionMessage(friend: LogFriendId, previous = ""): string {
  const pool = [...COMPANION_MESSAGES[friend], ...COMMON_COMPANION_MESSAGES];
  const choices = pool.filter(text => text !== previous);
  return choices[Math.floor(Math.random() * choices.length)];
}
