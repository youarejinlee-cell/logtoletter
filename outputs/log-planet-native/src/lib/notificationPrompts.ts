export const NOTIFICATION_PROMPTS_BY_PERIOD = {
  morning: MORNING_NOTIFICATION_PROMPTS,
  daytime: DAYTIME_NOTIFICATION_PROMPTS,
  evening: EVENING_NOTIFICATION_PROMPTS
} as const;

export function getNotificationPromptPeriod(minuteOfDay: number): NotificationPromptPeriod {
  const normalizedMinute = ((minuteOfDay % 1440) + 1440) % 1440;
  const hour = Math.floor(normalizedMinute / 60);
  if (hour >= 6 && hour < 12) return "morning";
  if (hour >= 18) return "evening";
  return "daytime";
}

export function createNotificationPromptSelector() {
  const offsets: Record<NotificationPromptPeriod, number> = {
    morning: Math.floor(Math.random() * MORNING_NOTIFICATION_PROMPTS.length),
    daytime: Math.floor(Math.random() * DAYTIME_NOTIFICATION_PROMPTS.length),
    evening: Math.floor(Math.random() * EVENING_NOTIFICATION_PROMPTS.length)
  };
  const counters: Record<NotificationPromptPeriod, number> = {
    morning: 0,
    daytime: 0,
    evening: 0
  };

  return (minuteOfDay: number) => {
    const period = getNotificationPromptPeriod(minuteOfDay);
    const prompts = NOTIFICATION_PROMPTS_BY_PERIOD[period];
    const index = (offsets[period] + counters[period]) % prompts.length;
    counters[period] += 1;
    return {
      id: period + "_" + String(index + 1).padStart(3, "0"),
      body: prompts[index]
    };
  };
}
